#!/usr/bin/env python3
"""Generate canonical-pair/combining data from Python's Unicode database."""
import pathlib
import unicodedata as ud
pairs=[];ranges=[]
for cp in range(0x110000):
    value=ud.decomposition(chr(cp)).split()
    if len(value)==2 and not value[0].startswith('<'):
        a,b=map(lambda x:int(x,16),value)
        if ud.normalize('NFC',chr(a)+chr(b))==chr(cp): pairs.append((a,b,cp))
    if ud.category(chr(cp)).startswith('M'):
        if ranges and ranges[-1][1]+1==cp: ranges[-1][1]=cp
        else: ranges.append([cp,cp])
assert all(second >= 0x300 for _,second,_ in pairs)
out=['// Generated by tools/fonts/unicode_tables.py; Unicode '+ud.unidata_version+'.',
     '// Unicode data terms: https://www.unicode.org/license.txt',
     '#pragma once','namespace vangers::text::unicode {',
     'struct Pair { char32_t first, second, composed; };',
     'inline constexpr Pair pairs[]{']
out += ['{0x%X,0x%X,0x%X},'%p for p in sorted(pairs)]
out += ['};','struct Range { char32_t first, last; };','inline constexpr Range marks[]{']
out += ['{0x%X,0x%X},'%tuple(r) for r in ranges]
out += ['};','} // namespace vangers::text::unicode','']
pathlib.Path('src/text/unicode_tables.h').write_text('\n'.join(out))
